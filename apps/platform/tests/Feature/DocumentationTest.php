<?php

namespace Tests\Feature;

use Illuminate\Support\Facades\Artisan;
use Symfony\Component\Finder\Finder;
use Tests\TestCase;

/**
 * The Markdown documentation, skills, AGENTS.md and llms.txt only link to
 * files that exist and only mention starter:* commands that exist.
 */
class DocumentationTest extends TestCase
{
    /**
     * @return array<string, string> path => contents
     */
    protected function documents(): array
    {
        $root = base_path('../..');
        $files = [];

        foreach ((new Finder)->files()->in(["{$root}/docs", "{$root}/skills"])->name('*.md') as $file) {
            $files[$file->getRealPath()] = $file->getContents();
        }

        foreach (['README.md', 'INSTALL.md', 'AGENTS.md', 'llms.txt'] as $name) {
            $files[realpath("{$root}/{$name}")] = (string) file_get_contents("{$root}/{$name}");
        }

        return $files;
    }

    public function test_relative_links_point_to_existing_files(): void
    {
        $broken = [];

        foreach ($this->documents() as $path => $contents) {
            // The specification is the source document, not generated by us...
            if (str_ends_with($path, 'especificacion.md')) {
                continue;
            }

            preg_match_all('/\]\(([^)\s#]+)(?:#[^)]*)?\)/', $contents, $matches);

            foreach ($matches[1] as $link) {
                if (preg_match('#^(https?:|mailto:|/)#', $link)) {
                    continue;
                }

                if (! file_exists(dirname($path).'/'.$link)) {
                    $broken[] = basename($path)." → {$link}";
                }
            }
        }

        $this->assertSame([], $broken);
    }

    public function test_documented_starter_commands_exist(): void
    {
        $commands = array_keys(Artisan::all());
        $missing = [];

        foreach ($this->documents() as $path => $contents) {
            preg_match_all('/\b(starter:[a-z][a-z-]+)/', $contents, $matches);

            foreach (array_unique($matches[1]) as $command) {
                if (! in_array($command, $commands, true)) {
                    $missing[] = basename($path)." → {$command}";
                }
            }
        }

        $this->assertSame([], $missing);
    }
}
