<?php

namespace Starter\Ai\Agents;

use Illuminate\Auth\Access\AuthorizationException;
use Illuminate\Contracts\JsonSchema\JsonSchema;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Validator;
use Illuminate\Validation\ValidationException;
use Laravel\Ai\Approvals\Approval;
use Laravel\Ai\Concerns\InteractsWithApprovals;
use Laravel\Ai\Contracts\Approvable;
use Laravel\Ai\Contracts\Tool;
use Laravel\Ai\Tools\Request;
use Starter\Ai\Models\ActionProposal;
use Stringable;
use Throwable;

/**
 * Base class of tools that operate the application from the chat.
 *
 * Subclasses validate their arguments (rules), may describe the change
 * (preview) and execute it through the same Actions as the panel and the
 * API (execute). The actor always comes from the server-side context.
 *
 * Reads run directly. Writes run directly unless the agent confirms every
 * change. Sensitive tools pause the run (SDK approval) and create a
 * proposal; they only execute after the user confirmed that proposal, with
 * the same arguments and an unchanged resource.
 */
abstract class OperatorTool implements Approvable, Tool
{
    use InteractsWithApprovals;

    public function __construct(
        protected ToolContext $context,
        protected ToolDefinition $definition,
        protected ActionProposals $proposals,
    ) {}

    public function name(): string
    {
        return $this->definition->name;
    }

    /**
     * Validation rules of the arguments generated by the model.
     *
     * @return array<string, mixed>
     */
    abstract protected function rules(): array;

    /**
     * Execute the change or the query and return verifiable data.
     *
     * @param  array<string, mixed>  $arguments
     * @return array<string, mixed>
     */
    abstract protected function execute(array $arguments): array;

    /**
     * Describe a change before it runs: target, before/after and effects.
     * Must authorize and fail like the real operation would.
     *
     * @param  array<string, mixed>  $arguments
     */
    protected function preview(array $arguments): ProposalPreview
    {
        return new ProposalPreview((string) $this->description());
    }

    /**
     * @return array<string, mixed>
     */
    abstract public function schema(JsonSchema $schema): array;

    abstract public function description(): Stringable|string;

    /**
     * Pause the call for confirmation when the tool requires it. Invalid or
     * unauthorized calls are not paused: they run and report their error.
     */
    protected function needsApproval(Request $request): Approval|bool
    {
        if (! $this->requiresConfirmation()) {
            return false;
        }

        $toolCallId = $request->toolCallId();

        if ($toolCallId === null) {
            return false;
        }

        // The SDK asks again when the run resumes: keep the same answer...
        if (($existing = $this->proposals->find($this->context, $toolCallId)) !== null) {
            return Approval::required($existing->preview['title']);
        }

        try {
            $arguments = $this->validated($request->all());
            $preview = $this->preview($arguments);
        } catch (Throwable) {
            return false;
        }

        $proposal = $this->proposals->propose($this->context, $this->definition, $toolCallId, $arguments, $preview);

        return Approval::required($proposal->preview['title']);
    }

    public function handle(Request $request): Stringable|string
    {
        $this->refreshActor();

        try {
            $arguments = $this->validated($request->all());
        } catch (ValidationException $exception) {
            return $this->respond(['ok' => false, 'error' => implode(' ', $exception->validator->errors()->all())]);
        }

        if (! $this->requiresConfirmation()) {
            return $this->run($arguments, null);
        }

        $proposal = $request->toolCallId() !== null ? $this->proposals->find($this->context, $request->toolCallId()) : null;

        if ($proposal === null || ! $this->proposals->claim($proposal)) {
            return $this->respond(['ok' => false, 'error' => 'This change was not confirmed by the user, so nothing was done.']);
        }

        if (ActionProposals::hash($arguments) !== $proposal->arguments_hash) {
            $this->proposals->failed($proposal, 'The arguments differ from the confirmed proposal.');

            return $this->respond(['ok' => false, 'error' => 'The arguments differ from the confirmed proposal, so nothing was done.']);
        }

        try {
            $current = $this->preview($arguments);
        } catch (Throwable $exception) {
            $this->proposals->failed($proposal, $exception);

            return $this->respond(['ok' => false, 'error' => $this->errorMessage($exception)]);
        }

        if ($current->resourceVersion !== $proposal->resource_version) {
            $this->proposals->failed($proposal, 'The resource changed after the proposal was prepared.');

            return $this->respond(['ok' => false, 'error' => 'The resource changed after the proposal was prepared, so nothing was done. Prepare it again if still needed.']);
        }

        return $this->run($arguments, $proposal);
    }

    /**
     * @param  array<string, mixed>  $arguments
     */
    protected function run(array $arguments, ?ActionProposal $proposal): string
    {
        try {
            $result = DB::transaction(fn () => $this->execute($arguments));
        } catch (Throwable $exception) {
            if ($proposal !== null) {
                $this->proposals->failed($proposal, $exception);
            }

            if (! $exception instanceof AuthorizationException && ! $exception instanceof ValidationException) {
                report($exception);
            }

            if ($this->definition->kind !== ToolKind::Read) {
                audit('ai.tool.failed', null, $this->auditContext($arguments, $proposal) + ['error' => $this->errorMessage($exception)], $this->context->actor);
            }

            return $this->respond(['ok' => false, 'error' => $this->errorMessage($exception)]);
        }

        if ($proposal !== null) {
            $this->proposals->executed($proposal, $result);
        }

        if ($this->definition->kind !== ToolKind::Read) {
            audit('ai.tool.executed', null, $this->auditContext($arguments, $proposal) + ['result' => $this->auditableResult($result)], $this->context->actor);
        }

        return $this->respond(['ok' => true] + $result);
    }

    protected function requiresConfirmation(): bool
    {
        return match ($this->definition->kind) {
            ToolKind::Read => false,
            ToolKind::Write => $this->context->config()->confirmWrites(),
            ToolKind::Sensitive => true,
        };
    }

    /**
     * @param  array<string, mixed>  $input
     * @return array<string, mixed>
     */
    protected function validated(array $input): array
    {
        /** @var array<string, mixed> */
        return Validator::make($input, $this->rules())->validate();
    }

    /**
     * Reload the actor so revoked roles or permissions apply immediately.
     */
    protected function refreshActor(): void
    {
        if ($this->context->actor instanceof Model) {
            $this->context->actor->unsetRelations();
        }
    }

    protected function errorMessage(Throwable $exception): string
    {
        return match (true) {
            $exception instanceof AuthorizationException => (string) __('You are not allowed to do this.'),
            $exception instanceof ValidationException => implode(' ', $exception->validator->errors()->all()),
            default => (string) __('The operation failed. Nothing was changed.'),
        };
    }

    /**
     * @param  array<string, mixed>  $arguments
     * @return array<string, mixed>
     */
    protected function auditContext(array $arguments, ?ActionProposal $proposal): array
    {
        return array_filter([
            'tool' => $this->definition->name,
            'agent' => $this->context->version->agent->slug ?? null,
            'agent_version_id' => $this->context->version->id,
            'ai_request_id' => $this->context->requestId,
            'proposal' => $proposal?->id,
            'target' => $proposal?->preview['target'] ?? null,
            'changes' => $proposal?->preview['changes'] ?? null,
            'arguments' => $arguments,
        ], fn (mixed $value) => $value !== null);
    }

    /**
     * @param  array<string, mixed>  $result
     * @return array<string, mixed>
     */
    protected function auditableResult(array $result): array
    {
        return array_intersect_key($result, array_flip(['id', 'user', 'role', 'invitation', 'message', 'url']));
    }

    /**
     * @param  array<string, mixed>  $data
     */
    protected function respond(array $data): string
    {
        return (string) json_encode($data, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    }
}
